#!/usr/bin/env python3
"""Rasterise the display icons into smalltv_monitor/display/icon_data.py (design-time only).

    .venv/bin/python -m pip install --require-hashes -r requirements-dev.txt   # cairosvg + Pillow
    .venv/bin/python scripts/build_icons.py

SVGs are downloaded from pinned npm packages via jsDelivr into icons/svg/ (kept in the repo, so a
rebuild works offline), rendered at 4x with cairosvg, downsampled to 16x16 alpha and quantised to
4 bits: the /v1/icon wire format of docs/WIDGET-PROTOCOL.md. Licences: docs/ICONS.md.
"""

from __future__ import annotations

import io
import sys
import urllib.request
from pathlib import Path

import cairosvg
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SVG_DIR = ROOT / "icons" / "svg"
OUT = ROOT / "smalltv_monitor" / "display" / "icon_data.py"

SIMPLE_ICONS = "https://cdn.jsdelivr.net/npm/simple-icons@15.22.0/icons/{}.svg"  # CC0-1.0
LUCIDE = "https://cdn.jsdelivr.net/npm/lucide-static@0.544.0/icons/{}.svg"  # ISC

# display name -> (source URL template, source icon name, padding px). Brand marks fill their viewBox
# edge to edge, Lucide icons already have 2/24 padding; the extra padding evens out their visual size.
ICONS = {
    "claude": (SIMPLE_ICONS, "claude", 1),
    "codex": (SIMPLE_ICONS, "openai", 1),
    "cursor": (SIMPLE_ICONS, "cursor", 1),
    "slack": (SIMPLE_ICONS, "slack", 1),
    "cpu": (LUCIDE, "cpu", 0),
    "mem": (LUCIDE, "memory-stick", 0),
    "disk": (LUCIDE, "hard-drive", 0),
    "gpu": (LUCIDE, "gpu", 0),
}
SIZE = 16
SUPERSAMPLE = 4

# Colour icons: Slack's own tray images (no dot / blue unread dot / red mention dot), read from the
# installed Slack desktop app (proprietary artwork, used for this personal display only).
SLACK_RESOURCES = Path("/snap/slack/current/usr/lib/slack/resources/app.asar.unpacked/dist/resources")
SLACK_VARIANTS = {"slack-rest": "rest", "slack-unread": "unread", "slack-mention": "highlight"}


def fetch(url: str, dest: Path) -> bytes:
    if not dest.exists():
        with urllib.request.urlopen(url, timeout=20) as resp:
            dest.write_bytes(resp.read())
    return dest.read_bytes()


def rasterise(svg: bytes, padding: int) -> bytes:
    inner = (SIZE - 2 * padding) * SUPERSAMPLE
    png = cairosvg.svg2png(bytestring=svg, output_width=inner, output_height=inner)
    alpha = Image.open(io.BytesIO(png)).convert("RGBA").getchannel("A")
    canvas = Image.new("L", (SIZE * SUPERSAMPLE, SIZE * SUPERSAMPLE), 0)
    canvas.paste(alpha, (padding * SUPERSAMPLE, padding * SUPERSAMPLE))
    small = canvas.resize((SIZE, SIZE), Image.LANCZOS)
    levels = [min(15, round(a / 17)) for a in small.get_flattened_data()]
    packed = bytes((levels[i] << 4) | (levels[i + 1] if i + 1 < len(levels) else 0) for i in range(0, len(levels), 2))
    return b"SI\x01" + bytes([SIZE, SIZE]) + packed


def colour_icon(image: Image.Image) -> bytes:
    """Format 0x02: up to 16 RGBA palette entries (RGB565 + alpha) and 4-bit indices."""
    rgba = image.convert("RGBA")
    quantised = rgba.quantize(colors=16, method=Image.Quantize.FASTOCTREE)
    used = len(quantised.getcolors())
    flat = quantised.getpalette(rawmode="RGBA")[: 4 * used]
    palette = b""
    for i in range(used):
        r, g, b, a = flat[4 * i : 4 * i + 4]
        rgb565 = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        palette += bytes([rgb565 >> 8, rgb565 & 0xFF, a])
    idx = list(quantised.get_flattened_data())
    packed = bytes((idx[i] << 4) | (idx[i + 1] if i + 1 < len(idx) else 0) for i in range(0, len(idx), 2))
    width, height = rgba.size
    return b"SI\x02" + bytes([width, height, used]) + palette + packed


def main() -> int:
    SVG_DIR.mkdir(parents=True, exist_ok=True)
    lines = [
        '"""Generated by scripts/build_icons.py; do not edit. Sources and licences: docs/ICONS.md.',
        "",
        "The slack-* images are Slack's own tray icons: Slack, its logo and artwork are trademarks and copyright",
        "of Slack Technologies, LLC, a Salesforce company, included only to show Slack's status on this display",
        "and not covered by this repository's licence. The brand marks (claude, codex, cursor, slack) are",
        'trademarks of their respective owners."""',
        "",
        "ICONS: dict[str, bytes] = {",
    ]
    for name, (template, source, padding) in ICONS.items():
        svg = fetch(template.format(source), SVG_DIR / f"{name}.svg")
        payload = rasterise(svg, padding)
        lines.append(f'    "{name}": bytes.fromhex("{payload.hex()}"),')
        print(f"{name:7} <- {template.format(source)}  ({len(payload)} bytes)")
    for name, variant in SLACK_VARIANTS.items():
        source = SLACK_RESOURCES / f"slack-taskbar-{variant}.ico"
        if not source.exists():
            print(f"{name:13} skipped: {source} not found (Slack desktop not installed)")
            continue
        ico = Image.open(source)
        ico.size = (SIZE, SIZE)  # use the native 16x16 frame
        payload = colour_icon(ico)
        lines.append(f'    "{name}": bytes.fromhex("{payload.hex()}"),')
        print(f"{name:13} <- {source.name}  ({len(payload)} bytes, colour)")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
